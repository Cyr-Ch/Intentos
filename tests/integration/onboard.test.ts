import { afterAll, beforeAll, describe, expect, it } from "vitest";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { onboardRepository, policyIdFor, renderDraftPolicy, runProbe } from "../../src/onboard.ts";
import { KnowledgeStore } from "../../src/knowledge/storage.ts";
import { loadPolicyFile } from "../../src/knowledge/policy.ts";
import { repoInterpreter, repoVenvDir } from "../../src/knowledge/venv.ts";
import { PROJECT_ROOT, resolvePython } from "../../src/config.ts";
import { setupFixtureEnv } from "../helpers/fixture.ts";

let home: string;
let repo: string;
let store: KnowledgeStore;

function write(rel: string, text: string): void {
  const p = path.join(repo, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, text);
}

beforeAll(() => {
  home = fs.mkdtempSync(path.join(os.tmpdir(), "intentos-onboard-"));
  process.env.INTENTOS_HOME = home;
  repo = path.join(home, "sample");
  fs.mkdirSync(repo);
  write("pyproject.toml", '[project]\nname = "sample_pkg"\nversion = "0.1.0"\ndependencies = []\n[tool.pytest.ini_options]\ntestpaths = ["tests"]\n');
  write("src/sample_pkg/__init__.py", "def add(a: int, b: int) -> int:\n    return a + b\n");
  write("tests/test_add.py", "from sample_pkg import add\n\n\ndef test_add():\n    assert add(1, 2) == 3\n");
  write("docs/README.md", "# Sample\n\n## Rules\n\nAddition is commutative.\n");
  write("README.md", "# sample\n");
  for (const args of [["init", "-q"], ["add", "-A"], ["-c", "user.email=t@t", "-c", "user.name=t", "commit", "-q", "-m", "init"]]) {
    const r = spawnSync("git", args, { cwd: repo, encoding: "utf8" });
    if (r.status !== 0) throw new Error(`git ${args.join(" ")}: ${r.stderr}`);
  }
  store = new KnowledgeStore(path.join(home, "intentos.db"));
});
afterAll(() => {
  store.close();
  delete process.env.INTENTOS_HOME;
  fs.rmSync(home, { recursive: true, force: true });
});

describe("intentos onboard", () => {
  it("drafts a policy for a src-layout repository, smoke-tests it and indexes it without installing anything", () => {
    const out = path.join(home, "drafts", "sample_pkg.yaml");
    const r = onboardRepository(store, repo, { install: false, test: true, index: true, force: false, out });
    expect(r.policy_id).toBe("sample_pkg");
    expect(r.policy_file).toBe(out);
    expect(r.policy_in_policies_dir).toBe(false);
    expect(r.venv).toBeNull();
    expect(r.interpreter).toBe(resolvePython());
    const policy = loadPolicyFile(out);
    expect(policy.policy_id).toBe("sample_pkg");
    expect(policy.applies_to).toEqual({ project_name: "sample_pkg", path_basename: "sample" });
    expect(policy.default_allowed_paths).toEqual(["src/**", "tests/**"]);
    expect(policy.protected_paths).toEqual(expect.arrayContaining(["docs/**", "pyproject.toml", "README.md"]));
    expect(policy.scope_tags).toEqual({ "src/sample_pkg/**": ["sample_pkg"], "tests/**": ["tests"] });
    expect(Object.keys(policy.commands).sort()).toEqual(["architecture_rules", "architecture_surprise", "pytest_project", "scope_check"]);
    expect(policy.commands.pytest_project!.argv).toEqual(["{python}", "-m", "pytest", "tests", "-q", "-p", "no:cacheprovider", "-o", "pythonpath=src", "--junit-xml={junit}"]);
    expect(policy.commands.architecture_surprise!.enforcement).toBe("advisory");
    expect(policy.invariants).toEqual([]);
    expect(policy.architecture_rules).toEqual([]);
    expect(policy.decisions).toEqual([]);
    expect(fs.readFileSync(out, "utf8")).toMatch(/DRAFT generated by `intentos onboard`/);
    expect(r.smoke.status).toBe("passed");
    expect(r.smoke.tests_passed).toBe(1);
    expect(r.smoke.tests_failed).toBe(0);
    expect(fs.existsSync(r.smoke.log_path!)).toBe(true);
    expect(r.index!.mode).toBe("full");
    expect(r.index!.counts["nodes.symbol"]).toBeGreaterThan(0);
    expect(r.warnings.join("\n")).toMatch(/fallback policy/); // written outside policies/
    expect(r.next_steps.join("\n")).toMatch(/move .*sample_pkg\.yaml/);
    expect(r.next_steps.join("\n")).toMatch(/intentos explain/);
  });

  it("refuses to overwrite an existing draft without --force and reports a failing suite honestly", () => {
    const out = path.join(home, "drafts", "sample_pkg.yaml");
    expect(() => onboardRepository(store, repo, { install: false, test: false, index: false, force: false, out })).toThrow(/--force/);
    // break the test, re-onboard with --force: the smoke result must say failed, never passed
    write("tests/test_add.py", "from sample_pkg import add\n\n\ndef test_add():\n    assert add(1, 2) == 4\n");
    const r = onboardRepository(store, repo, { install: false, test: true, index: false, force: true, out });
    expect(r.smoke.status).toBe("failed");
    expect(r.smoke.tests_failed).toBe(1);
    expect(r.warnings.join("\n")).toMatch(/did not pass/);
    write("tests/test_add.py", "from sample_pkg import add\n\n\ndef test_add():\n    assert add(1, 2) == 3\n");
  });

  it("onboards the startup_billing fixture (flat layout) with the pytest configuration it declares", () => {
    const env = setupFixtureEnv(); // its own INTENTOS_HOME
    try {
      const out = path.join(env.home, "drafts", "startup_billing.yaml");
      const r = onboardRepository(env.store, env.repo, { install: false, test: true, index: false, force: false, out });
      expect(r.policy_id).toBe("startup_billing");
      const policy = loadPolicyFile(out);
      expect(policy.default_allowed_paths).toEqual(["app/**", "tests/**"]);
      expect(policy.protected_paths).toEqual(expect.arrayContaining(["docs/**", "pyproject.toml", "README.md"]));
      expect(policy.commands.pytest_project!.argv).toContain("pythonpath=.");
      expect(r.probe.layout).toBe("flat");
      expect(r.probe.packages).toEqual(["app"]);
      expect(r.smoke.status).toBe("passed");
      expect(r.smoke.tests_passed).toBeGreaterThan(10);
    } finally {
      env.cleanup();
      process.env.INTENTOS_HOME = home;
    }
  });

  it("the verifier prefers the repository's onboarded venv, then INTENTOS_PYTHON overrides everything", () => {
    const venv = repoVenvDir(repo);
    fs.mkdirSync(path.join(venv, "bin"), { recursive: true });
    fs.writeFileSync(path.join(venv, "bin", "python"), "");
    try {
      expect(repoInterpreter(repo)).toBe(path.join(venv, "bin", "python"));
      const prev = process.env.INTENTOS_PYTHON;
      process.env.INTENTOS_PYTHON = "/override/python";
      try {
        expect(repoInterpreter(repo)).toBe("/override/python");
      } finally {
        if (prev === undefined) delete process.env.INTENTOS_PYTHON;
        else process.env.INTENTOS_PYTHON = prev;
      }
    } finally {
      fs.rmSync(venv, { recursive: true, force: true });
    }
    expect(repoInterpreter(repo)).toBe(resolvePython());
    expect(repoInterpreter(null)).toBe(resolvePython());
  });

  it("renders a draft that parses even for a repository without packaging metadata", () => {
    const probe = runProbe(repo);
    const bare = { ...probe, name: null, packages: [], package_dirs: [], test_paths: [], test_dirs: [], pythonpath: [], protected_candidates: [], layout: "flat" as const };
    const file = path.join(home, "drafts", "bare.yaml");
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, renderDraftPolicy(bare, repo, policyIdFor(bare, repo)));
    const policy = loadPolicyFile(file);
    expect(policy.policy_id).toBe("sample");
    expect(policy.default_allowed_paths).toEqual(["**"]);
    expect(policy.commands.pytest_project!.argv).toContain("pythonpath=.");
  });

  it("normalises declared testpaths and never lets a doctest root collide with protected paths", () => {
    const probe = runProbe(repo);
    const declared = { ...probe, test_paths: ["src/", "./tests/", "docs/"], test_dirs: ["tests"], pytest: { ...probe.pytest, source: "pyproject.toml:[tool.pytest.ini_options]", addopts: "--doctest-modules\n    --strict-markers" } };
    const file = path.join(home, "drafts", "declared.yaml");
    fs.writeFileSync(file, renderDraftPolicy(declared, repo, "declared"));
    const policy = loadPolicyFile(file);
    expect(policy.default_allowed_paths).toEqual(["src/**", "tests/**"]);
    expect(policy.scope_tags).toEqual({ "src/sample_pkg/**": ["sample_pkg"], "tests/**": ["tests"] });
    expect(policy.commands.pytest_project!.argv.slice(3, 6)).toEqual(["src", "tests", "docs"]);
    expect(fs.readFileSync(file, "utf8")).toMatch(/addopts "--doctest-modules --strict-markers"/);
    expect(fs.readFileSync(file, "utf8")).not.toMatch(/\/\/\*\*/);
  });

  it("is wired into the CLI with --json", () => {
    const out = path.join(home, "drafts", "cli.yaml");
    const res = spawnSync("node", ["--disable-warning=ExperimentalWarning", path.join(PROJECT_ROOT, "bin", "intentos.js"), "--json", "onboard", repo, "--no-install", "--no-test", "--no-index", "--force", "--out", out], { encoding: "utf8", env: { ...process.env, INTENTOS_HOME: home } });
    expect(res.status, res.stderr).toBe(0);
    const parsed = JSON.parse(res.stdout) as { policy_id: string; smoke: { status: string }; index: unknown };
    expect(parsed.policy_id).toBe("sample_pkg");
    expect(parsed.smoke.status).toBe("skipped");
    expect(parsed.index).toBeNull();
    expect(fs.existsSync(out)).toBe(true);
  });
});
