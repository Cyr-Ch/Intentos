/**
 * mergeguard inside IntentOS: coordination between runs that share one repository.
 *
 * IntentOS verifies one run against one base revision. mergeguard (a Python package, `pip install -e`'d into the
 * IntentOS venv) answers the question IntentOS cannot: is this change still safe to merge now that other runs have
 * landed on main? It runs in "local mode": the indexed repository is origin, its checked-out branch is main, every
 * run's worktree is a branch in waiting, and all mergeguard state (PR registry, ledger, trusted policy) lives under
 * INTENTOS_HOME, never inside the repository the agents edit.
 *
 *   - during IMPLEMENTING/REPAIRING: hook files in the worktree tell the Codex thread about API changes merged on
 *     main while it works (PostToolUse) and refuse to let it finish stale (Stop); SessionStart carries the ledger memory
 *   - during VERIFYING: the same sync check is a blocking finding, and the router's review tier is recorded
 *   - `intentos merge`: branch, PR, tier, approvals, merged-result verification, fast-forward of main, ledger
 *   - `intentos guard`: guardian (reruns, first-parent bisect, partner search, validated undo PR) and breaker floors
 */
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import YAML from "yaml";
import type { Policy } from "../knowledge/policy.ts";
import { resolvePaths, resolvePython } from "../config.ts";
import { currentBranch, git, repoToplevel } from "../util/git.ts";
import { ensureDir } from "../util/paths.ts";

export interface CoordinationEnv {
  /** Environment variables that put mergeguard in local mode for this repository. */
  env: Record<string, string>;
  /** Branch of the repository that plays main. */
  mainBranch: string;
  stateDir: string;
  policyFile: string;
  python: string;
}

let available: { ok: boolean; reason: string } | null = null;

/** Whether coordination is on: INTENTOS_COORDINATION is not "0" and mergeguard imports in the verifier interpreter. */
export function coordinationStatus(): { ok: boolean; reason: string } {
  if (process.env.INTENTOS_COORDINATION === "0") return { ok: false, reason: "INTENTOS_COORDINATION=0" };
  if (available) return available;
  const python = resolvePython();
  const res = spawnSync(python, ["-c", "import mergeguard, sys; print(mergeguard.__file__)"], { encoding: "utf8" });
  available = res.status === 0 ? { ok: true, reason: `mergeguard at ${res.stdout.trim()}` } : { ok: false, reason: `mergeguard is not importable by ${python} (${(res.stderr || "").trim().split("\n").pop() ?? "import failed"}); install it with: ${python} -m pip install -e <path to mergeguard>` };
  return available;
}

export function coordinationEnabled(): boolean {
  return coordinationStatus().ok;
}

/** Reset the cached availability probe (tests). */
export function resetCoordinationProbe(): void {
  available = null;
}

function repoId(repoPath: string): string {
  return path.basename(path.resolve(repoPath)).replace(/[^A-Za-z0-9_.-]/g, "_");
}

/**
 * mergeguard's trusted policy, rendered from the IntentOS policy: the same protected paths need two humans at the
 * merge, IntentOS itself is the trusted author (its verifier already ran), and additive code may merge unseen.
 */
export function renderMergeguardPolicy(policy: Policy): string {
  const protectedPaths = policy.protected_paths.map((p) => p.replace(/\*\*$/, "").replace(/\*$/, "")).filter(Boolean);
  const doc = {
    trusted_authors: ["intentos"],
    always_two: [...new Set([...protectedPaths, ".github/workflows/", ".codex/", ".claude/", ".mergeguard/"])],
    always_one: [],
    zero_review_allowed: true,
    zero_review_additive: true,
    prompter_counts_as_reviewer: false,
    api_break_tier: 2,
    breaker: { window_days: 7, strikes_to_trip: 2, cooldown_days: 14 },
  };
  return `# Generated by IntentOS from policy ${policy.policy_id}; edit the IntentOS policy, not this file.\n` + YAML.stringify(doc);
}

/** Environment for mergeguard commands against `repoPath` (local mode). Writes the policy file when missing or stale. */
export function coordinationEnv(repoPath: string, policy: Policy): CoordinationEnv {
  const repo = repoToplevel(repoPath);
  const mainBranch = currentBranch(repo) ?? "main";
  const stateDir = ensureDir(path.join(resolvePaths().home, "coordination", repoId(repo)));
  const policyFile = path.join(stateDir, "policy.yaml");
  const rendered = renderMergeguardPolicy(policy);
  if (!fs.existsSync(policyFile) || fs.readFileSync(policyFile, "utf8") !== rendered) fs.writeFileSync(policyFile, rendered);
  const python = resolvePython();
  return {
    env: { MERGEGUARD_MAIN: mainBranch, MERGEGUARD_STATE_DIR: stateDir, MERGEGUARD_POLICY_FILE: policyFile, MERGEGUARD_FETCH_INTERVAL: process.env.INTENTOS_COORDINATION_FETCH_INTERVAL ?? "15" },
    mainBranch,
    stateDir,
    policyFile,
    python,
  };
}

export interface MergeguardCall {
  ok: boolean;
  status: number | null;
  json: unknown;
  stdout: string;
  stderr: string;
  argv: string[];
}

/** Run `python -m mergeguard <args> --json` in `cwd` with the coordination environment. */
export function mergeguard(coord: CoordinationEnv, cwd: string, args: string[], opts: { timeoutMs?: number } = {}): MergeguardCall {
  const argv = [coord.python, "-m", "mergeguard", "--repo", cwd, ...args, "--json"];
  const env = { ...process.env, ...coord.env };
  delete env.MERGEGUARD_DISABLE;
  const res = spawnSync(argv[0]!, argv.slice(1), { cwd, env, encoding: "utf8", timeout: opts.timeoutMs ?? 600_000, maxBuffer: 64 * 1024 * 1024 });
  let parsed: unknown = null;
  try {
    parsed = res.stdout.trim() ? JSON.parse(res.stdout) : null;
  } catch {
    parsed = null;
  }
  return { ok: res.status === 0, status: res.status, json: parsed, stdout: res.stdout ?? "", stderr: res.stderr ?? "", argv };
}

function expectJson<T>(call: MergeguardCall, what: string): T {
  if (call.json === null) throw new Error(`mergeguard ${what} produced no JSON (exit ${call.status}): ${(call.stderr || call.stdout).trim().split("\n").slice(-3).join(" | ")}`);
  const err = (call.json as { error?: string }).error;
  if (err) throw new Error(`mergeguard ${what}: ${err}`);
  return call.json as T;
}

export interface SyncIssue {
  id: string;
  symbol: string;
  change: string;
  new: string | null;
  commit: string;
  used_in: string[];
  message: string;
}
export interface SyncResult {
  clean: boolean;
  base: string;
  main: string;
  issues: SyncIssue[];
}

/** The sync check of a worktree's working tree against the repository's main (no fetch; refs are shared). */
export function syncCheck(coord: CoordinationEnv, worktree: string): SyncResult {
  return expectJson<SyncResult>(mergeguard(coord, worktree, ["sync-check"]), "sync-check");
}

export interface RouteDecision {
  tier: number;
  required_approvals: number;
  reasons: string[];
  paths: string[];
  proofs: Record<string, string>;
  base: string;
  head: string;
  author: string;
  existing_tests_modified: boolean;
}

/** Review tier for the diff base..head as mergeguard's router sees it under the trusted policy. */
export function route(coord: CoordinationEnv, worktree: string, base: string, head: string, author = "intentos"): RouteDecision {
  return expectJson<RouteDecision>(mergeguard(coord, worktree, ["route", "--base", base, "--head", head, "--author", author]), "route");
}

export interface InstalledHooks {
  files: string[];
  /** `-c` override that trusts exactly these hook definitions, pinned by hash, for this invocation only. */
  trustOverride: string;
  remove: () => string[];
}

/** Install the agent hook files into a worktree; `remove()` deletes them again before the tree is inspected. */
export function installHooks(coord: CoordinationEnv, worktree: string): InstalledHooks {
  const out = expectJson<{ files: string[]; trust_override: string }>(mergeguard(coord, worktree, ["hooks", "install", worktree, "--python", coord.python]), "hooks install");
  return {
    files: out.files,
    trustOverride: out.trust_override,
    remove: () => expectJson<{ removed: string[] }>(mergeguard(coord, worktree, ["hooks", "remove", worktree]), "hooks remove").removed,
  };
}

export interface CodexHome {
  /** Directory to pass as CODEX_HOME for the turn: the run's hooks, hooks enabled, the user's auth by symlink. */
  home: string;
  files: string[];
  /** `-c` override trusting exactly these hook definitions by hash, for this process only. */
  trustOverride: string;
}

/**
 * A private CODEX_HOME for one implementer turn. Codex reads project `.codex/` only under a `.git` directory, and a
 * worktree's `.git` is a file, so hooks written into the worktree are never seen there; `$CODEX_HOME/hooks.json` is
 * read for any working directory. The user's own ~/.codex is never modified; its auth.json is linked, not copied.
 */
export function prepareCodexHome(coord: CoordinationEnv, dir: string): CodexHome {
  const out = expectJson<{ codex_home: string; files: string[]; trust_override: string }>(mergeguard(coord, path.dirname(dir), ["hooks", "home", dir, "--python", coord.python]), "hooks home");
  return { home: out.codex_home, files: out.files, trustOverride: out.trust_override };
}

export interface MergeguardPr {
  number: number;
  branch: string;
  title: string;
  head: string;
  author: string;
  prompter: string | null;
  state: "open" | "merged" | "closed";
  approvals: Array<{ user: string; head: string; kind: string; ts: string }>;
  decision: RouteDecision;
  sync: SyncResult;
  gate: { allowed: boolean; reasons: string[] };
  ci: { head: string; outcome: string; failed: string[]; summary: string };
  checked_main: string;
  merge_commit?: string;
  reverts?: string;
  min_tier?: number;
  merge_check?: { command: string; merged: string; outcome: string; summary: string } | null;
}

export function openPr(coord: CoordinationEnv, worktree: string, branch: string, title: string, opts: { author?: string; prompter?: string | null; minTier?: number; minTierReason?: string } = {}): MergeguardPr {
  const args = ["pr", "open", "--branch", branch, "--title", title, "--author", opts.author ?? "intentos"];
  if (opts.prompter) args.push("--prompter", opts.prompter);
  if (opts.minTier) args.push("--min-tier", String(opts.minTier), "--min-tier-reason", opts.minTierReason ?? "required by the caller");
  return expectJson<MergeguardPr>(mergeguard(coord, worktree, args), "pr open");
}

export function approvePr(coord: CoordinationEnv, cwd: string, number: number, user: string): MergeguardPr {
  return expectJson<MergeguardPr>(mergeguard(coord, cwd, ["pr", "approve", String(number), "--user", user]), "pr approve");
}

export function checkPr(coord: CoordinationEnv, cwd: string, number: number): MergeguardPr {
  const call = mergeguard(coord, cwd, ["pr", "check", String(number)]);
  return expectJson<MergeguardPr>(call, "pr check");
}

export function showPr(coord: CoordinationEnv, cwd: string, number: number): MergeguardPr {
  return expectJson<MergeguardPr>(mergeguard(coord, cwd, ["pr", "show", String(number)]), "pr show");
}

export function listPrs(coord: CoordinationEnv, cwd: string): MergeguardPr[] {
  return expectJson<MergeguardPr[]>(mergeguard(coord, cwd, ["pr", "list"]), "pr list");
}

export function mergePr(coord: CoordinationEnv, cwd: string, number: number, mergeCheck?: string): MergeguardPr {
  const saved = process.env.MERGEGUARD_MERGE_CHECK;
  if (mergeCheck) process.env.MERGEGUARD_MERGE_CHECK = mergeCheck;
  else delete process.env.MERGEGUARD_MERGE_CHECK;
  try {
    return expectJson<MergeguardPr>(mergeguard(coord, cwd, ["pr", "merge", String(number)], { timeoutMs: 1_800_000 }), "pr merge");
  } finally {
    if (saved === undefined) delete process.env.MERGEGUARD_MERGE_CHECK;
    else process.env.MERGEGUARD_MERGE_CHECK = saved;
  }
}

export interface GuardianResult {
  status: string;
  message?: string;
  culprit?: string | null;
  partner?: { commit: string | null; reason?: string } | null;
  pr?: number | null;
  partner_pr?: number | null;
  undo_pr?: number | null;
  failing?: string[];
  flaky_tests?: string[];
  steps?: number;
  [key: string]: unknown;
}

export function guardian(coord: CoordinationEnv, cwd: string, good: string, bad: string, opts: { undo?: boolean } = {}): GuardianResult {
  const args = ["guardian", "--good", good, "--bad", bad];
  if (opts.undo === false) args.push("--no-undo");
  const call = mergeguard(coord, cwd, args, { timeoutMs: 1_800_000 });
  return expectJson<GuardianResult>(call, "guardian");
}

