export interface LedgerEvent {
  ts: string;
  type: string;
  pr?: number | null;
  commit?: string | null;
  paths: string[];
  tier?: number;
  partner_pr?: number | null;
  details: Record<string, unknown>;
}

export function readLedger(coord: CoordinationEnv): LedgerEvent[] {
  const file = path.join(coord.stateDir, "ledger.jsonl");
  if (!fs.existsSync(file)) return [];
  return fs
    .readFileSync(file, "utf8")
    .split("\n")
    .filter((l) => l.trim())
    .map((l) => JSON.parse(l) as LedgerEvent);
}

/**
 * The worktree may only move its HEAD along main's own history: a sync (`git merge --ff-only <main>`) the hook asked
 * for. Any other HEAD is still an integrity failure for verification. Returns the new base when it advanced.
 */
export function syncedBase(repoPath: string, worktree: string, baseSha: string, mainBranch: string): string | null {
  const head = git(worktree, ["rev-parse", "HEAD"]).stdout.trim();
  if (head === baseSha) return null;
  const descendsFromBase = git(worktree, ["merge-base", "--is-ancestor", baseSha, head], { allowFail: true }).status === 0;
  const onMain = git(repoPath, ["merge-base", "--is-ancestor", head, mainBranch], { allowFail: true }).status === 0;
  return descendsFromBase && onMain ? head : null;
}
