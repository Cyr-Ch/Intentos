def build(root: Path, index: int, files: dict) -> tuple[Path, str, str]:
    repo = root / f"case-{index}"
    repo.mkdir()
    git(repo, "init", "--quiet", "--initial-branch=main")
    git(repo, "config", "user.name", "engineer_a")
    git(repo, "config", "user.email", "engineer_a@example.test")
    for path, source in BASE_FILES.items():
        write(repo, path, source)
    write(repo, ".mergeguard/policy.yaml", yaml.safe_dump(POLICY, sort_keys=False))
    write(repo, ".codex/hooks.json", "{\"hooks\": {\"Stop\": []}}\n")
    write(repo, ".claude/settings.json", "{\"hooks\": {\"Stop\": []}}\n")
    base = commit(repo, "Base")
    git(repo, "update-ref", "refs/remotes/origin/main", base)
    git(repo, "checkout", "--quiet", "-b", "feature")
    for path, source in files.items():
        if source is None:
            (repo / path).unlink()
        else:
            write(repo, path, source)
    head = commit(repo, "Change")
    return repo, base, head


def route_labelled(root: Path) -> dict:
    rows = []
    for index, (name, files, author, expected, risky, howmade) in enumerate(LABELLED):
        repo, base, head = build(root, index, files)
        decision = router.route(repo, base, head, author, howmade_data=howmade)
        rows.append({"name": name, "paths": decision["paths"], "author": author, "expected": expected, "actual": decision["tier"],
                     "risky": risky, "reasons": decision["reasons"], "ok": decision["tier"] == expected})
    total = len(rows)
    return {"rows": rows, "total": total, "exact": sum(r["ok"] for r in rows),
            "too_low": [r["name"] for r in rows if r["actual"] < r["expected"]],
            "risky_too_low": [r["name"] for r in rows if r["risky"] and r["actual"] < r["expected"]],
            "risky_total": sum(r["risky"] for r in rows),
            "too_high": [r["name"] for r in rows if r["actual"] > r["expected"]],
            "by_tier": {tier: sum(r["actual"] == tier for r in rows) for tier in (0, 1, 2)}}


def breaker_timeline() -> dict:
    policy = {**POLICY, "breaker": {"window_days": 7, "strikes_to_trip": 2, "cooldown_days": 14}}
    day0 = datetime(2026, 10, 1, tzinfo=timezone.utc)
    stamp = lambda days: (day0 + timedelta(days=days)).isoformat().replace("+00:00", "Z")  # noqa: E731
    events = [{"ts": stamp(0), "type": "culprit", "pr": 7, "commit": "aaa", "paths": ["payments/charge.py"], "details": {"incident": "aaa"}},
              {"ts": stamp(0), "type": "reverted", "pr": 7, "commit": "aaa", "paths": ["payments/charge.py"], "details": {"incident": "aaa"}},
              {"ts": stamp(3), "type": "culprit", "pr": 9, "commit": "bbb", "paths": ["payments/charge.py"], "details": {"incident": "bbb"}}]
    events += [{"ts": stamp(d), "type": "merged", "pr": 100 + d, "commit": f"m{d}", "paths": ["catalog.py"], "tier": 1, "details": {}} for d in range(1, 22)]
    def floors(day):
        return breaker.status(None, policy=policy, events=events, at=day0 + timedelta(days=day))["folders"]
    timeline = {"day1_after_one_incident": floors(1).get("payments/", {}).get("floor"),
                "day4_after_two_incidents": floors(4).get("payments/", {}).get("floor"),
                "day18_cooldown_complete": floors(18).get("payments/", {}).get("cooldown_complete"),
                "day18_floor_still_set": floors(18).get("payments/", {}).get("floor"),
                "day60_floor_still_set": floors(60).get("payments/", {}).get("floor"),
                "automatic_loosening": breaker.status(None, policy=policy, events=events, at=day0 + timedelta(days=60))["automatic_loosening"],
                "suggestions_day22": breaker.suggest(None, policy=policy, events=events, at=day0 + timedelta(days=22))}
    reset = {**policy, "breaker": {**policy["breaker"], "resets": {"payments/": stamp(19)}}}
    timeline["floor_after_human_reset_day20"] = breaker.status(None, policy=reset, events=events, at=day0 + timedelta(days=20))["folders"].get("payments/", {}).get("floor")
    return timeline


def pytest_counts(targets: list[str]) -> dict:
    started = time.perf_counter()
    result = subprocess.run([sys.executable, "-m", "pytest", "-q", *targets], cwd=ROOT, text=True, capture_output=True)
    tail = (result.stdout.strip().splitlines() or [""])[-1]
    return {"targets": targets, "exit_code": result.returncode, "summary_line": tail, "seconds": round(time.perf_counter() - started, 1)}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parent)
    args = parser.parse_args()
    timestamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S.%fZ")
    with tempfile.TemporaryDirectory(prefix="mergeguard-policy-") as directory:
        routing = route_labelled(Path(directory))
    summary = {"timestamp": timestamp, "kind": "policy", "router": routing, "breaker": breaker_timeline(),
               "guardian_tests": pytest_counts(["tests/test_guardian.py"]), "breaker_tests": pytest_counts(["tests/test_ledger_breaker.py"])}
    raw = args.output / "runs" / f"{timestamp}-policy"
    raw.mkdir(parents=True, exist_ok=True)
    atomic_json(raw / "summary.json", summary)
    render.write(args.output)
    print(f"Router: {routing['exact']}/{routing['total']} exact, risky too low: {routing['risky_too_low']}, too low: {routing['too_low']}, too high: {routing['too_high']}")
    print(f"Breaker: {json.dumps(summary['breaker'])}")
    print(f"Tests: {summary['guardian_tests']['summary_line']} | {summary['breaker_tests']['summary_line']}")
    return 0 if not routing["risky_too_low"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
