"""Author-controlled evidence can raise risk; absence never proves safety."""
from __future__ import annotations

import json
from pathlib import Path
import re
import subprocess

from .git import git, lock, metadata_dir
from .ledger import now


def append(repo, event: str, **data) -> dict:
    record = {"ts": now(), "event": event, "branch": git(repo, "branch", "--show-current"), **data}
    path = metadata_dir(repo) / "howmade.jsonl"
    with lock(path.with_suffix(".lock")):
        with path.open("a") as stream:
            stream.write(json.dumps(record) + "\n")
    return record


def read(repo, branch: str | None = None) -> list[dict]:
    path = metadata_dir(repo) / "howmade.jsonl"
    if not path.exists():
        return []
    branch = branch or git(repo, "branch", "--show-current")
    with lock(path.with_suffix(".lock")):
        return [row for line in path.read_text().splitlines() if line.strip()
                and (row := json.loads(line)).get("branch", branch) == branch]


def is_test(cmd: str) -> bool:
    return bool(re.search(r"(?:^|[\s/;&|])pytest(?:\s|$)", cmd))


def summarize(events: list[dict], *, files: int = 0, tests_modified: bool = False) -> dict:
    tests = [e for e in events if e.get("event") == "command" and is_test(e.get("cmd", ""))]
    first = next((i for i, e in enumerate(tests, 1) if e.get("exit_code") == 0), None)
    notes = [e for e in events if e.get("event") == "sync_note"]
    return {"test_runs": len(tests), "first_pass": first, "sync_notes": len(notes),
            "notes": [n.get("message", "") for n in notes], "existing_tests_modified": tests_modified, "files_changed": files}


def markdown(summary: dict) -> str:
    first = f"first pass on attempt {summary['first_pass']}" if summary["first_pass"] else "no recorded pass"
    return ("## How it was made (generated by mergeguard)\n"
            f"- test runs: {summary['test_runs']} ({first})\n"
            f"- sync notes received: {summary['sync_notes']}\n"
            f"- existing tests modified: {'yes' if summary['existing_tests_modified'] else 'no'}\n"
            f"- files changed: {summary['files_changed']}\n" +
            "".join(f"  - {note}\n" for note in summary.get("notes", [])))


def parse(text: str) -> dict:
    """Parse numeric raises even if there are multiple author-written sections."""
    def largest(pattern):
        return max([int(n) for n in re.findall(pattern, text, re.I)] or [0])
    return {"test_runs": largest(r"test runs:\s*(\d+)"), "sync_notes": largest(r"sync notes received:\s*(\d+)"),
            "existing_tests_modified": bool(re.search(r"existing tests modified:\s*yes", text, re.I))}


def run_command(repo, command: list[str]) -> int:
    """Optional receipt wrapper when Codex's hook payload omits the exit status."""
    import shlex
    from .git import root
    if command and command[0] == "--":
        command = command[1:]
    if not command:
        raise ValueError("run requires a command, for example: mergeguard run -- python -m pytest -q")
    result = subprocess.run(command, cwd=root(repo))
    append(repo, "command", cmd=shlex.join(command), exit_code=result.returncode, source="run-receipt")
    return result.returncode
